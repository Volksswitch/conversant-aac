// Copies the British spellings, words and phrases from writing-conventions.json into
// app/data/slip-words.json, which the app loads to check talk answers for British
// wording (question sessions, November 9 2026). writing-conventions.json is the one
// list; this is a copy the deployed app can reach. Run after editing those lists:
//   node scripts/apply-slip-words.mjs
// tests/question-session.test.mjs fails if the two differ.
import fs from 'node:fs';

const c = JSON.parse(fs.readFileSync('writing-conventions.json', 'utf8'));
const out = {
    _README: 'GENERATED by scripts/apply-slip-words.mjs from writing-conventions.json. Do not edit by hand.',
    words: [...c.britishSpellings, ...c.britishVocabulary].map(([b, a]) => [b, a]),
    phrases: (c.britishPhrases || []).map(([b, a]) => [b, a]),
};
fs.writeFileSync('app/data/slip-words.json', JSON.stringify(out, null, 2) + '\n');
console.log(`wrote app/data/slip-words.json: ${out.words.length} words, ${out.phrases.length} phrases`);
