#!/usr/bin/env node
/*
 * make-tablet-table.mjs — copy the keyguard designer's tablet list into the app.
 *
 * Trigger phrase: "update tablet list".
 *
 * The keyguard designer (keyguard.scad) holds, for every tablet it supports, the
 * screen's size in pixels and the size of one pixel in millimetres (item 17 of the
 * tablet's data vector: [short side px, long side px, mm per pixel]). The app uses the
 * same numbers so that the millimetres shown beside a spacing setting are the
 * millimetres the keyguard is built with (Ken, November 27 2026).
 *
 * The tablet NAMES and their ORDER come from the list in `type_of_tablet` (what the
 * designer shows); the numbers come from `tablet_table` and the `*_data` constants.
 * "blank" and "other tablet" are left out.
 *
 * Usage: node scripts/make-tablet-table.mjs [path to keyguard.scad]
 * With no path it looks in the Keyguard project folder beside this one, found from
 * the OneDrive folder, so it runs unchanged on either machine.
 *
 * Writes app/js/tablets.js. A tablet named in the list with no numbers, or numbers
 * that do not make sense, stops the run and is named, rather than being dropped.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');

function defaultScad() {
    const od = process.env.OneDrive || process.env.ONEDRIVE || '';
    return path.join(od, '4 T-Z', 'Volksswitch', 'Keyguard', 'My SCAD files',
        'keyguard designer', 'keyguard.scad');
}

const scadPath = process.argv[2] || defaultScad();
if (!fs.existsSync(scadPath)) {
    console.error(`Cannot find the keyguard designer at:\n  ${scadPath}\nPass its path as an argument.`);
    process.exit(1);
}
const src = fs.readFileSync(scadPath, 'utf8');

// 1. The names, in the designer's own order.
const listLine = src.split(/\r?\n/).find(l => /^\s*type_of_tablet\s*=/.test(l));
if (!listLine) { console.error('No type_of_tablet line found.'); process.exit(1); }
const listMatch = listLine.match(/\/\/\s*\[(.*)\]\s*$/);
if (!listMatch) { console.error('type_of_tablet has no [list] comment.'); process.exit(1); }
const names = listMatch[1].split(',').map(s => s.trim()).filter(Boolean)
    .filter(n => n !== 'blank' && n !== 'other tablet');

// 2. Every top-level `name_data = ...;` definition: a vector, or another constant.
const defs = new Map();
for (const line of src.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*_data)\s*=\s*(.+?);\s*(\/\/.*)?$/);
    if (m) defs.set(m[1], m[2].trim());
}
function resolve(id, seen = new Set()) {
    if (seen.has(id)) throw new Error(`circular definition at ${id}`);
    seen.add(id);
    const v = defs.get(id);
    if (v === undefined) throw new Error(`no definition for ${id}`);
    if (/^[A-Za-z_]/.test(v)) return resolve(v, seen);
    return JSON.parse(v);
}

// 3. The name -> constant table.
const tStart = src.indexOf('tablet_table');
const tOpen = src.indexOf('[', tStart);
const tEnd = src.indexOf('];', tOpen);
const tableText = src.slice(tOpen, tEnd);
const rowRe = /\[\s*"([^"]+)"\s*,\s*([A-Za-z_][A-Za-z0-9_]*)\s*\]/g;
const table = new Map();
for (let m; (m = rowRe.exec(tableText));) table.set(m[1], m[2]);

const out = [];
const problems = [];
for (const name of names) {
    const id = table.get(name);
    if (!id) { problems.push(`${name}: not in tablet_table`); continue; }
    let vec;
    try { vec = resolve(id); } catch (e) { problems.push(`${name}: ${e.message}`); continue; }
    const px = vec[17];
    if (!Array.isArray(px) || px.length < 3) { problems.push(`${name}: item 17 is not [short, long, mm]`); continue; }
    const [a, b, mm] = px.map(Number);
    if (!(a > 0 && b > 0 && mm > 0 && mm < 1)) { problems.push(`${name}: odd numbers ${JSON.stringify(px)}`); continue; }
    out.push({ name, short: Math.min(a, b), long: Math.max(a, b), mmPerPx: mm });
}
if (problems.length) {
    console.error('Not written - these tablets could not be read:\n  ' + problems.join('\n  '));
    process.exit(1);
}

const body = out.map(t =>
    `    { name: ${JSON.stringify(t.name)}, short: ${t.short}, long: ${t.long}, mmPerPx: ${t.mmPerPx} },`
).join('\n');
const js = `/*
 * tablets.js — GENERATED by scripts/make-tablet-table.mjs from the keyguard designer
 * (keyguard.scad). Do not edit by hand; run "update tablet list" instead.
 *
 * Each tablet: its screen in device pixels (short side, long side) and the size of one
 * device pixel in millimetres, exactly as the keyguard designer uses them, so the
 * millimetres the app shows are the millimetres a keyguard is built with.
 */
export const TABLETS = [
${body}
];
`;
const dest = path.join(root, 'app', 'js', 'tablets.js');
fs.writeFileSync(dest, js);
console.log(`Wrote ${out.length} tablets to ${path.relative(root, dest)}`);
